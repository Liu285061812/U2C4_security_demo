/*===========================================================================
  ICU-M test function
  [PUBLIC]
  ===========================================================================*/
void icum_hash_time_test(void)
{
    int n;
    
    printf("\n\nTest hashing...\n");
       
    while(1)
    {
        printf("\n| select hash test\n");
        printf("|---------------------------------\n");
        printf("| 1   : hash_MD5_test\n");
        printf("| 2   : hash_RIPEMD128_test\n");
        printf("| 3   : hash_RIPEMD160_test\n");
        printf("| 4   : hash_RIPEMD256_test\n");
        printf("| 5   : hash_RIPEMD320_test\n");
        printf("| 6   : hash_SHA1_test\n");
        printf("| 7   : hash_SHA2_224_test\n");
        printf("| 8   : hash_SHA2_256_test\n");
        printf("| 9   : hash_SHA2_384_test\n");
        printf("| 10  : hash_SHA2_512_test\n");
        printf("| q   : Quit\n\n");
        printf("    ?> ");
        vrun_console_get();

        if(*(char *)vrun_iobuff_readparam(0) == 'q')
        {
            break;
        }
        else
        {
            sscanf(vrun_iobuff_readparam(0), "%i", &n);
        }
        
        // pause life signal management
        pause_life_signal();
        
        switch(n)
        {
            case 1: hash_MD5_test();        break;
            case 2: hash_RIPEMD128_test();  break;
            case 3: hash_RIPEMD160_test();  break;
            case 4: hash_RIPEMD256_test();  break;
            case 5: hash_RIPEMD320_test();  break;
            case 6: hash_SHA1_test();       break;
            case 7: hash_SHA2_224_test();   break;
            case 8: hash_SHA2_256_test();   break;
            case 9: hash_SHA2_384_test();   break;
            case 10:hash_SHA2_512_test();   break;
            default:    break;
        }

        // restart life signal
        restart_life_signal();
    }
}


static void hash_MD5_test()
{
    r_icumif_isd_t     *p_ISD;
    int n;
    
    printf("MD5 Test\n");
    
    for(n = 0; n < 2; n++)
    {
        // initialize the global icum service header
        p_ISD = (r_icumif_isd_t *)ISD_BUFFER;
        memset(ISD_BUFFER, 0, SIZE_OF_ISD_BUFFER);//clear the ISD_BUFFER
        
        p_ISD->service_id                     = SERVICE_01_HASH;
        p_ISD->p_callbackfunc                 = 0;
        p_ISD->job_id                         = 0;
        
        if(n == 0){
            p_ISD->prm.HASH.message_size_in_bytes = 32;
            p_ISD->prm.HASH.p_message             = _32_byte_msg;
            printf("\nmessage size 32byte\n");
        }
        else if(n == 1){
            p_ISD->prm.HASH.message_size_in_bytes = 4096;
            p_ISD->prm.HASH.p_message             = _4k_byte_msg;
            printf("\nmesssage size 4096byte\n");
        }
        p_ISD->prm.HASH.hash_primitive        = HASH_PRIMITIVE_MD5;
        p_ISD->prm.HASH.job_slice             = job_slice[JOB_H];
        p_ISD->prm.HASH.p_hash                = BIG_BUFFER[0];
        
        vrun_chrono_start();
        trigger_service_and_wait(p_ISD);
        vrun_chrono_stop();
        
        vrun_chrono_gettimestamp();
        printf("Processed in : "); PCHRONO(); NL(); FLUSH();
        print_throughput(p_ISD->prm.HASH.message_size_in_bytes);
    }
}


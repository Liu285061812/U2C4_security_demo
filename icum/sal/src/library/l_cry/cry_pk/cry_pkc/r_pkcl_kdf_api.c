#define PKCL_KDF_HASH_LEN_SHA2_256      (32U)             /**< SHA2-256 hash byte length */
#define PKCL_KDF_HASH_LEN_MAX           (PKCL_KDF_HASH_LEN_SHA2_256)    /**< Maximum hash length in supported */
#define PKCL_KDF_SHARED_SECRET_LEN_MIN  (1U)              /**< Minimum size of shared secret generated by PKC-Lib */
#define PKCL_KDF_SHARED_SECRET_LEN_MAX  (68U)             /**< Maximum size of shared secret generated by PKC-Lib */
#define PKCL_KDF_OUT_LEN_MIN            (1U)              /**< Minimum size of output key */
#define PKCL_KDF_OUT_LEN_MAX            (1024U)           /**< Maximum size of output key */

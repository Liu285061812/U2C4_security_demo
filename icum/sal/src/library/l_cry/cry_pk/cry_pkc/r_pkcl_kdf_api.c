/*!****************************************************************************************************************//**
 * \ingroup     PKCLKDFAPIsInternal
 * \brief       Check the argument of #R_PKCL_KdfSp80056c.
 * \param       [in]   p_ctx                A structure that summarizes the parameters required for KDF calculation.
 * \param       [in]   p_shared_secret      A shared secret
 * \param       [in]   shared_secret_len    Shared secret byte length
 * \param       [in]   out_len              Output byte length
 * \param       [in]  p_out_key             Address of the buffer that outputs the shared key
 * \return
 *  - 0x55555555:                       Successful completion
 *  - 0xAAAAAAAA:                       Processing failed
 * \par Security components
 *  - No
 * \par Global Variables
 *  - None
 * \par Call PKC-Driver API
 *  - None
 * \par Precondition
 *  - None
 * \par Detailed description
 *  - Check the argument of #R_PKCL_KdfSp80056c.
 * \par Remarks
 *  - None
 *
 * Pseudo-code for the function can be found below.
 *  -# Initialize the variable ret with #PKCL_EXTERNAL_API_ERR.
 *  -# If ((NULL != p_ctx) and (NULL != p_shared_secret) and (NULL != p_out_key))
 *    -# If ((#PKCL_KDF_SHARED_SECRET_LEN_MIN <= shared_secret_len) and
 *           (shared_secret_len <= #PKCL_KDF_SHARED_SECRET_LEN_MAX))
 *      -# If ((#PKCL_KDF_OUT_LEN_MIN <= out_len) and (out_len <= #PKCL_KDF_OUT_LEN_MAX))
 *        -# If (NULL != p_ctx->p_hash_info)
 *          -# If (#PKC_HASH_TYPE_SHA2_256 == p_ctx->hash_type)
 *            -# If ((NULL != p_ctx->p_hash_info->p_hash_init_api) and
 *                   (NULL != p_ctx->p_hash_info->p_hash_update_api) and
 *                   (NULL != p_ctx->p_hash_info->p_hash_final_api))
 *              -# If (!((NULL == p_ctx->p_fixed_info) and (0U != p_ctx->fixed_info_len)))
 *                -# Set the variable ret to #PKCL_EXTERNAL_API_OK.
 *              -# Else
 *                -# Set the variable ret to #PKCL_EXTERNAL_API_ERR.
 *            -# Else
 *              -# Set the variable ret to #PKCL_EXTERNAL_API_ERR.
 *          -# Else
 *            -# Set the variable ret to #PKCL_EXTERNAL_API_ERR.
 *        -# Else
 *          -# Set the variable ret to #PKCL_EXTERNAL_API_ERR.
 *      -# Else
 *        -# Set the variable ret to #PKCL_EXTERNAL_API_ERR.
 *    -# Else
 *      -# Set the variable ret to #PKCL_EXTERNAL_API_ERR.
 *  -# Else
 *    -# Set the variable ret to #PKCL_EXTERNAL_API_ERR.
 *
 * \callgraph
 *********************************************************************************************************************/
static uint32_t r_pkcl_kdf_chk_sp800_56c_arg(const st_pkcl_kdf_sp800_56c_ctx_t* const p_ctx,
                                                const uint8_t* const    p_shared_secret,
                                                const uint32_t          shared_secret_len,
                                                const uint32_t          out_len,
                                                const uint8_t* const    p_out_key)
{
    uint32_t ret = PKCL_EXTERNAL_API_ERR;

    /* Check argument except contex */
    if ((NULL != p_ctx) && (NULL != p_shared_secret) && (NULL != p_out_key))
    {
        if ((PKCL_KDF_SHARED_SECRET_LEN_MIN <= shared_secret_len) &&
            (shared_secret_len <= PKCL_KDF_SHARED_SECRET_LEN_MAX))
        {
            if ((PKCL_KDF_OUT_LEN_MIN <= out_len) &&
                (out_len <= PKCL_KDF_OUT_LEN_MAX))
            {
                if (NULL != p_ctx->p_hash_info)
                {
                    if (PKC_HASH_TYPE_SHA2_256 == p_ctx->hash_type)
                    {
                        if ((NULL != p_ctx->p_hash_info->p_hash_init_api) &&
                            (NULL != p_ctx->p_hash_info->p_hash_update_api) &&
                            (NULL != p_ctx->p_hash_info->p_hash_final_api))
                        {
                            if (!((NULL == p_ctx->p_fixed_info) && (0U != p_ctx->fixed_info_len)))
                            {
                                ret = PKCL_EXTERNAL_API_OK;
                            }
                            else
                            {
                                ret = PKCL_EXTERNAL_API_ERR;
                            }
                        }
                        else
                        {
                            ret = PKCL_EXTERNAL_API_ERR;
                        }
                    }
                    else
                    {
                        ret = PKCL_EXTERNAL_API_ERR;
                    }
                }
                else
                {
                    ret = PKCL_EXTERNAL_API_ERR;
                }
            }
            else
            {
                ret = PKCL_EXTERNAL_API_ERR;
            }
        }
        else
        {
            ret = PKCL_EXTERNAL_API_ERR;
        }
    }
    else
    {
        ret = PKCL_EXTERNAL_API_ERR;
    }

    return ret;
}

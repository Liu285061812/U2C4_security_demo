static uint32_t r_pkcl_kdf_chk_sp800_56c_arg (const st_pkcl_kdf_sp800_56c_ctx_t * const p_ctx,
                                                const uint8_t * const    p_shared_secret,
                                                const uint32_t           shared_secret_len,
                                                const uint32_t           out_len,
                                                const uint8_t * const    p_out_key);
static uint32_t r_pkcl_kdf_get_hash_len (const e_pkc_hash_type_t hash_type);

/**********************************************************************************************************************
* Function Name : R_PKCL_KdfSp80056c
**********************************************************************************************************************/
uint32_t R_PKCL_KdfSp80056c(void* const             p_kdf_ctx,
                            const uint8_t* const    p_shared_secret,
                            const uint32_t          shared_secret_len,
                            const uint32_t          out_len,
                            uint8_t* const          p_out_key)
{
    uint32_t ret = PKCL_EXTERNAL_API_ERR;
    uint32_t counter;
    uint32_t counber_be;
    uint32_t reps;
    uint32_t hash_len;
    uint32_t md_len;
    uint32_t cpy_len;
    uint32_t i;
    uint8_t md[PKCL_KDF_HASH_LEN_MAX];
    const st_pkc_hash_t * p_hi;

    /* No problem with casting to pointer size */
    const st_pkcl_kdf_sp800_56c_ctx_t * const p_ctx = (st_pkcl_kdf_sp800_56c_ctx_t*)p_kdf_ctx;

    /* Check argument except contex */
    ret = r_pkcl_kdf_chk_sp800_56c_arg(p_ctx, p_shared_secret, shared_secret_len, out_len, p_out_key);
    if (PKCL_EXTERNAL_API_OK == ret)
    {
        /* Get Hash len */
        hash_len = r_pkcl_kdf_get_hash_len(p_ctx->hash_type);
        if (0U != hash_len)
        {
            p_hi = p_ctx->p_hash_info;

            /* Calculate rsps */
            reps = out_len / hash_len;
            if (0U != (out_len % hash_len))
            {
                reps++;
            }
            else
            {
                /* Do nothign */
            }

            counter = 0U;
            for (i = 0U; (i < reps) && (PKCL_EXTERNAL_API_OK == ret); i++ )
            {
                /* Increment counter by 1.*/
                counter++;

                /* change big endian */
                counber_be = r_pkcl_cmn_ch_big_endian32(counter);

                ret = p_hi->p_hash_init_api(p_hi->p_hash_ctx);
                if (PKCL_EXTERNAL_API_OK == ret)
                {
                    /* No problem with casting to pointer size */
                    ret = p_hi->p_hash_update_api(p_hi->p_hash_ctx, (uint8_t*)&counber_be, sizeof(uint32_t));
                    if (PKCL_EXTERNAL_API_OK == ret)
                    {
                        ret = p_hi->p_hash_update_api(p_hi->p_hash_ctx, p_shared_secret, shared_secret_len);
                        if (PKCL_EXTERNAL_API_OK == ret)
                        {
                            if (0U != p_ctx->fixed_info_len)
                            {
                                ret = p_hi->p_hash_update_api(p_hi->p_hash_ctx,
                                                                p_ctx->p_fixed_info, p_ctx->fixed_info_len);
                            }
                            else
                            {
                                /* Do nothing */
                            }
                            if (PKCL_EXTERNAL_API_OK == ret)
                            {
                                ret = p_hi->p_hash_final_api(p_hi->p_hash_ctx, md, &md_len);
                            }
                            else
                            {
                                /* Do nothing */
                            }
                        }
                        else
                        {
                            /* Do nothing */
                        }
                    }
                    else
                    {
                        /* Do nothing */
                    }
                }
                else
                {
                    /* Do nothing */
                }

                if (PKCL_EXTERNAL_API_OK == ret)
                {
                    if (((reps - 1U) == i) && (0U != (out_len % hash_len)))
                    {
                        cpy_len = out_len % hash_len;
                    }
                    else
                    {
                        cpy_len = hash_len;
                    }
                    r_pkcl_cmn_cpy_byte(&p_out_key[(hash_len * i) ], md, cpy_len);
                }
                else
                {
                    /* Do nothing */
                }
            }
        }
        else
        {
            ret = PKCL_EXTERNAL_API_ERR;
        }
    }
    else
    {
        /* Do nothing */
    }

    return ret;
}

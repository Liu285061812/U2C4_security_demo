/*!****************************************************************************************************************//**
 * \ingroup     PKCLKDFAPIsInternal
 * \brief       Get hash byte lengh.
 * \param       [in]   hash_type            Hash type
 * \return
 *  - Hash byte length of the specified type
 * \par Security components
 *  - No
 * \par Global Variables
 *  - None
 * \par Call PKC-Driver API
 *  - None
 * \par Precondition
 *  - None
 * \par Detailed description
 *  - Get hash byte lengh of specified type.
 * \par Remarks
 *  - None
 *
 * Pseudo-code for the function can be found below.
 *  -# If (hash_type == PKC_HASH_TYPE_SHA2_256)
 *    -# Set the variable hash_len to #PKCL_KDF_HASH_LEN_SHA2_256.
 *  -# Else
 *    -# Set hash_len to 0U.
 *  -# Return hash_len.
 *
 * \callgraph
 *********************************************************************************************************************/
static uint32_t r_pkcl_kdf_get_hash_len(const e_pkc_hash_type_t hash_type)
{
    uint32_t hash_len;

    switch (hash_type)
    {
        case PKC_HASH_TYPE_SHA2_256:
            hash_len = PKCL_KDF_HASH_LEN_SHA2_256;
            break;
        default:
            hash_len = 0U;
            break;
    }

    return hash_len;
}

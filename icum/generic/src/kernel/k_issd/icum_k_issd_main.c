typedef enum{
    T_HASH_SHA1,
    T_HASH_SHA224,
    T_HASH_SHA256,
    T_HASH_SHA512,
}HASH_TYPE_T;

void hash_generate(const unsigned char *msg, uint32_t msg_len, HASH_TYPE_T type, uint8_t *digest)
{
     /*-----------------------------------------------------------------------------------------------------------------
     Local variables
    -----------------------------------------------------------------------------------------------------------------*/
    e_r_hash_ret_t ret;

    uint32_t i=0;
    uint32_t j=0;
    const uint32_t *p_temp = msg;
    uint8_t *digest_out = digest;

    uint32_t reg_val = 0;
    uint32_t reg_val1 = 0;
    uint32_t reg_val2 = 0;

    uint8_t hash_mode = 0;
    uint8_t last_idata_num = 0;
    uint32_t roundup_len;
    uint32_t last_roundup_len;
    uint32_t loop_time = 0;
    uint32_t message_len =0;
    uint32_t hash_len = 0;

    uint32_t block_size;

    block_size = BLOCK_SIZE_ERR;
    message_len = msg_len;

    uint32_t temp=0;

    /*-----------------------------------------------------------------------------------------------------------------
     Function body
    -----------------------------------------------------------------------------------------------------------------*/
    /* ICUMX_SHAA initialize and mode set and endian set */

    register volatile uint32_t *pICUM_IMR;
    register volatile uint32_t ulpsw_u;

    pICUM_IMR = (volatile uint32_t *)&ICUM_INTC1.ICUM_IMR0.UINT32;

    /* 2. Random number generation completion interrupt disable */
    *pICUM_IMR = (*pICUM_IMR | 0x1000000);

    /* Dummy read & Synchronize pipeline to wait for the completion of */
    /* writing to the ICUM_IMR0 register                               */
    (void)(*pICUM_IMR);
    SYNC_PIPELINE();
    ICUM_CTLREGICUM_GPIO &= 0xFFFE;
 //   ulpsw_u = STSR(PSW);
 //   ulpsw_u &= 0xDFFF;
 //   LDSR(ulpsw_u, PSW);
    reg_val = ICUM_SHASTS;
    switch(type)
    {
        case T_HASH_SHA1:
            hash_mode = 0;
            block_size = BLOCK_SIZE_64_BYTE;
            hash_len = 20;
            break;
        case T_HASH_SHA224:
            hash_mode = 4;
            block_size = BLOCK_SIZE_64_BYTE;
            hash_len = 28;
            break;
        case T_HASH_SHA256:
            hash_mode = 5;
            block_size = BLOCK_SIZE_64_BYTE;
            hash_len = 32;
            break;
        default:
            hash_mode = 5;
            block_size = BLOCK_SIZE_128_BYTE;
            hash_len = 64;
            break;
    }
    ICUM_CTLREGICUM_GPIO |= 0x01;
    ICUM_SHACNT =  (0x1U << CNT_INIT_POS) | (hash_mode << CNT_MODE_POS);  //0x10000000;
    SYNC_PIPELINE();
    ICUM_CTLREGICUM_GPIO &= 0xFFFE;
    ICUM_SHACNT |= (0x1U << CNT_ENDIAN_POS); // set endian to 0 from 1 zhxk
//    ICUM_SHACNT = (0x1U << CNT_INIT_POS) | (0x5U << CNT_MODE_POS) | (0x1U << CNT_ENDIAN_POS);
    ICUM_CTLREGICUM_GPIO |= 0x01;
//    reg_val2 = ICUM_SHACNT;
    while((ICUM_SHAFIFOCNT & 0x1000)!=0x0){};
    ICUM_CTLREGICUM_GPIO &= 0xFFFE;
    while((ICUM_SHASTS & 0x10) != 0x10){};     /* wait for the state to change */
    ICUM_CTLREGICUM_GPIO |= 0x01;
    roundup_len = r_hash_cmn_roundup_4(message_len);
    if (BLOCK_SIZE_ERR == block_size)
    {
        ret = HASH_RET_LENGTHERR;
    }
    else
    {
        /* set input data(last block) */
        if (REMAINING_DATA_CHECK_0 == message_len)
        {
            /* Define macro ICUM_SHADCNT is cast to access a register */
            ICUM_SHADCNT =  (REGISTER_SET_1 << DCNT_IDATA_LAST_POS) |
                            (REGISTER_SET_1 << DCNT_HASH_GET_POS)   |
                            (REGISTER_SET_1 << DCNT_IDATA_ZERO_POS);
        }
        else
        {
            last_idata_num = message_len % HASH_WORD_SIZE;
            last_idata_num *= BYTE2BIT_VAL;
            if(roundup_len<=block_size)
            {
               /* Define macro ICUM_SHADCNT is cast to access a register */
               ICUM_SHADCNT =  (REGISTER_SET_1 << DCNT_IDATA_LAST_POS) |
                            (REGISTER_SET_1 << DCNT_HASH_GET_POS)   |
                            (last_idata_num << DCNT_IDATA_NUM_POS);
                for(i = 0U; i < roundup_len/4; i++)
                {
                    /* Define macro ICUM_SHAIDAT is cast to access a register */
                    if(i==(roundup_len/4-1))
                    {
 //                        temp = p_temp[i]&(0xFFFFFFFF>>last_idata_num);
                         ICUM_SHAIDAT = p_temp[i]&(0xFFFFFFFF>>last_idata_num);
                    }    
                    else
                    {
                        ICUM_SHAIDAT = p_temp[i];
                    }    
//                    reg_val1 = ICUM_SHAIDAT;
                }
                ICUM_SHAFIFOCNT = (REGISTER_SET_1 << FIFOCNT_IDAT_POS);
            }
            else
            {
                loop_time = (roundup_len+63)/64;
                last_roundup_len = (roundup_len%64)/4;      /*the length of the last message block in 32bit size*/
                if(last_roundup_len==0)
                    last_roundup_len = 16;
                ICUM_CTLREGICUM_GPIO &= 0xFFFE;    
                for(i=0;i<loop_time-1;i++)
                {
                    while((ICUM_SHASTS & 0x10) != 0x10){};     /* wait for the state to change */
                    for(j = 0U; j < 16; j++)
                    {
                        /* Define macro ICUM_SHAIDAT is cast to access a register */
                        ICUM_SHAIDAT = p_temp[i*16+j];
//                        reg_val1 = ICUM_SHAIDAT;
                    }   
                }
                ICUM_CTLREGICUM_GPIO |= 0x01;
                /*The last message block */
                /* Define macro ICUM_SHADCNT is cast to access a register */
                ICUM_SHADCNT =  (REGISTER_SET_1 << DCNT_IDATA_LAST_POS) |
                            (REGISTER_SET_1 << DCNT_HASH_GET_POS)   |
                            (last_idata_num << DCNT_IDATA_NUM_POS);
                    /* set the data to IDAT register */
                while((ICUM_SHASTS & 0x10) != 0x10){};     /* wait for the state to change */
                for(i = 0U; i < last_roundup_len; i++)
                {
                    /* Define macro ICUM_SHAIDAT is cast to access a register */
                    if(i == (last_roundup_len-1))
                        ICUM_SHAIDAT = p_temp[i]&(0xFFFFFFFF>>last_idata_num);
                    else
                        ICUM_SHAIDAT = p_temp[i];
                }
                /* When processing data length(round up multiple of 4) is not equal the block size, */
                /* transfer FIFO data to SHAA0 core.                                                */
                if (last_roundup_len != 16)
                {
                    /* Define macro ICUM_SHAFIFOCNT is cast to access a register */
                    ICUM_SHAFIFOCNT = (REGISTER_SET_1 << FIFOCNT_IDAT_POS);
                    reg_val1 = ICUM_SHAFIFOCNT;
                }

            }
        }
    }
    ICUM_CTLREGICUM_GPIO &= 0xFFFE;
 //   reg_val = ICUM_SHASTS;
 //   reg_val2 = ICUM_SHACNT;
    /* get output data */
    ret = r_hash_cmn_get_output_data(hash_len, digest_out);
    reg_val = ICUM_SHASTS;
    ICUM_CTLREGICUM_GPIO |= 0x01;
}


"""Generate dedicated boot data and two public-demo AES-CMACs, independently of existing tests."""
import hashlib
import re
from pathlib import Path

from Crypto.Cipher import AES
from Crypto.Hash import CMAC

ROOT = Path(__file__).resolve().parents[1]
BOOT = ROOT / "boot_auth"
INPUT_BYTES = 10 * 1024


def demo_keys():
    source = (BOOT / "boot_auth_demo_keys.h").read_text(encoding="ascii")
    keys = []
    for name in ("ICUM", "PE"):
        match = re.search(
            rf"#define BOOT_AUTH_{name}_KEY_BYTES (.*?)(?=\n#define|\n\n)",
            source, re.S)
        if match is None:
            raise ValueError(f"Missing {name} demonstration key")
        key = bytes(int(value, 16) for value in re.findall(r"0x([0-9A-Fa-f]{2})u", match[1]))
        if len(key) != 16:
            raise ValueError(f"{name} demonstration key must contain 16 bytes")
        keys.append(key)
    if keys[0] == keys[1]:
        raise ValueError("Boot authentication requires different ICUM and PE keys")
    return keys


def boot_data():
    data = hashlib.shake_256(b"U2C4 dedicated boot authentication data v1").digest(INPUT_BYTES)
    tags = []
    for key in demo_keys():
        mac = CMAC.new(key, ciphermod=AES)
        mac.update(data)
        tags.append(mac.digest())
    return data, *tags


def main():
    parts = boot_data()
    lines = [
        "/* Generated by tools/generate_boot_auth_data.py; public demo data only. */",
        '#include "boot_auth.h"',
        "",
        '#pragma ghs section rodata=".boot_auth_data"',
        "const boot_auth_data_t g_boot_auth_data = {",
    ]
    for part in parts:
        lines.append("    {")
        for offset in range(0, len(part), 16):
            lines.append("        " + ", ".join(f"0x{v:02X}u" for v in part[offset:offset + 16]) + ",")
        lines.append("    },")
    lines += ["};", "#pragma ghs section rodata=default", ""]
    (BOOT / "boot_auth_data.c").write_text("\n".join(lines), encoding="ascii")
    print(f"Boot input: {len(parts[0])} bytes; image: {sum(map(len, parts))} bytes")
    print(f"ICUM CMAC: {parts[1].hex().upper()}")
    print(f"PE   CMAC: {parts[2].hex().upper()}")


if __name__ == "__main__":
    main()

"""Generate public ACEU board-test oracles (requires PyCryptodome and cryptography)."""
from pathlib import Path

from Crypto.Cipher import AES
from Crypto.Hash import CMAC
from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / r"pe\generic\src\pe1\src\pe1_aceu_vectors.h"


def oracle(mode, slot, length, aad_length=0, nonce_length=12, tag_length=16):
    key = bytes(range(16 + slot * 8))
    data = bytes(i & 255 for i in range(length))
    iv = bytes(range(16))
    aad = bytes((0xA0 + i) & 255 for i in range(aad_length))
    tag = bytes(16)
    if mode <= 4:
        cipher = (
            lambda: AES.new(key, AES.MODE_ECB),
            lambda: AES.new(key, AES.MODE_CBC, iv=iv),
            lambda: AES.new(key, AES.MODE_CTR, nonce=b"", initial_value=iv),
            lambda: AES.new(key, AES.MODE_CFB, iv=iv, segment_size=128),
            lambda: AES.new(key, AES.MODE_OFB, iv=iv),
        )[mode]()
        output = cipher.encrypt(data)
    elif mode == 6:
        second = bytes(range(0x20, 0x20 + len(key)))
        encryptor = Cipher(algorithms.AES(key + second), modes.XTS(iv)).encryptor()
        output = encryptor.update(data) + encryptor.finalize()
    elif mode in (5, 7, 10):
        aes_mode = AES.MODE_CCM if mode == 7 else AES.MODE_GCM
        cipher = AES.new(key, aes_mode, nonce=iv[:nonce_length], mac_len=tag_length)
        cipher.update(aad)
        output, tag = cipher.encrypt_and_digest(data)
    elif mode == 8:
        mac = CMAC.new(key, ciphermod=AES)
        mac.update(data)
        tag, output = mac.digest(), b""
    elif mode == 9:
        state = bytes(16)
        for offset in range(0, length, 16):
            block = data[offset:offset + 16]
            encrypted = AES.new(state, AES.MODE_ECB).encrypt(block)
            state = bytes(x ^ y ^ z for x, y, z in zip(encrypted, block, state))
        tag, output = state, b""
    else:
        output = AES.new(key, AES.MODE_OFB, iv=iv).encrypt(bytes(length))
    return output, tag.ljust(16, b"\0")


def cases():
    for mode in range(12):
        slots = (0, 2) if mode == 6 else ((0,) if mode == 9 else (0, 1, 2))
        for slot in slots:
            lengths = [32, 10240]
            if mode <= 4:
                lengths += [16]
            if mode in (2, 3, 4, 5, 7, 8):
                lengths += [31]
            if mode in (5, 7, 8):
                lengths += [0]
            if mode == 6:
                lengths += [16, 31, 10239]
            if mode == 10:
                lengths = [0]
            for length in lengths:
                aad_length = 17 if mode in (5, 7) else (10240 if mode == 10 else 0)
                nonce_length = 12 if mode in (5, 7, 10) else 16
                output, tag = oracle(mode, slot, length, aad_length, nonce_length)
                yield mode, slot, length, aad_length, nonce_length, 16, output, tag
            if mode in (5, 7):
                for length in (0, 31):
                    nonce_length = 7 if mode == 7 else 12
                    output, tag = oracle(mode, slot, length, 0, nonce_length, 8)
                    yield mode, slot, length, 0, nonce_length, 8, output, tag
                nonce_length = 13 if mode == 7 else 12
                output, tag = oracle(mode, slot, 31, 17, nonce_length, 4)
                yield mode, slot, 31, 17, nonce_length, 4, output, tag


def main():
    lines = ["/* Generated by tools/generate_aceu_vectors.py; public test vectors only. */"]
    vectors = list(cases())
    for index, (_, _, _, _, _, _, output, _) in enumerate(vectors):
        if not output:
            continue
        lines.append(f"static const uint8_t s_aceu_expected_{index}[] = {{")
        for offset in range(0, len(output), 16):
            lines.append("    " + ", ".join(f"0x{x:02X}u" for x in output[offset:offset + 16]) + ",")
        lines.append("};")
    lines.append("static const aceu_vector_t s_aceu_vectors[] = {")
    for index, (mode, slot, length, aad_length, nonce_length, tag_length, output, tag) in enumerate(vectors):
        values = ", ".join(f"0x{x:02X}u" for x in tag)
        expected = f"s_aceu_expected_{index}" if output else "0"
        lines.append(
            f"    {{ {mode}u, {slot}u, {length}u, {aad_length}u, {nonce_length}u, "
            f"{tag_length}u, {expected}, {{ {values} }} }},")
    lines += ["};", ""]
    DEST.write_text("\n".join(lines), encoding="ascii")
    print(f"Generated {len(vectors)} ACEU oracle cases, {sum(len(v[6]) for v in vectors)} expected bytes")


if __name__ == "__main__":
    main()
